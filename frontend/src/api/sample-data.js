// Calculate payment status from the registration fee and amount paid.
function getPaymentStatus(registration) {
  if (registration.amountPaid === 0) {
    return "Unpaid";
  }

  if (registration.amountPaid < registration.registrationFee) {
    return "Partial";
  }

  return "Paid";
}

// Get registrations with search, filters, and pagination.
export async function getRegistrations({
  participantName = "",
  type = "",
  status = "",
  page = 1,
  pageSize = 10,
} = {}) {
  let filteredRegistrations = [...registrations];

  // Search by participant name.
  if (participantName.trim()) {
    filteredRegistrations = filteredRegistrations.filter(
      (registration) =>
        registration.participantName
          .toLowerCase()
          .includes(participantName.trim().toLowerCase())
    );
  }

  // Filter by registration type.
  if (type && type !== "All") {
    filteredRegistrations = filteredRegistrations.filter(
      (registration) => registration.registrationType === type
    );
  }

  // Filter by registration status.
  if (status && status !== "All") {
    filteredRegistrations = filteredRegistrations.filter(
      (registration) => registration.status === status
    );
  }

  const totalCount = filteredRegistrations.length;
  const totalPages = Math.ceil(totalCount / pageSize);

  // Make sure the requested page is valid.
  const currentPage = Math.min(
    Math.max(1, Number(page) || 1),
    Math.max(1, totalPages)
  );

  const startIndex = (currentPage - 1) * pageSize;

  const items = filteredRegistrations
    .slice(startIndex, startIndex + pageSize)
    .map((registration) => ({
      ...registration,
      paymentStatus: getPaymentStatus(registration),
    }));

  return {
    items,
    page: currentPage,
    pageSize,
    totalCount,
    totalPages,
  };
}

// Get dashboard totals from all registrations, not just the current page.
export async function getSummary() {
  const totalRegistrations = registrations.length;

  const confirmed = registrations.filter(
    (registration) => registration.status === "Confirmed"
  ).length;

  const checkedIn = registrations.filter(
    (registration) => registration.status === "CheckedIn"
  ).length;

  const pending = registrations.filter(
    (registration) => registration.status === "Pending"
  ).length;

  const cancelled = registrations.filter(
    (registration) => registration.status === "Cancelled"
  ).length;

  const totalFees = registrations.reduce(
    (total, registration) => total + registration.registrationFee,
    0
  );

  const totalPayments = registrations.reduce(
    (total, registration) => total + registration.amountPaid,
    0
  );

  const uncollectedPayments = totalFees - totalPayments;

  return {
    totalRegistrations,
    confirmed,
    checkedIn,
    pending,
    cancelled,
    totalFees,
    totalPayments,
    uncollectedPayments,
  };
}
